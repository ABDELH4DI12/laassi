const normalise = (name) => String(name).toLowerCase()
  .replace(/\+/g, "plus").replace(/#/g, "sharp").replace(/\./g, "dot").replace(/[^a-z0-9]/g, "");

// The Simple Icons entry for a skill or stack item ({ title, hex, path } on a 24×24 grid), or null.
export function techIcon(name, explicit) {
  if (explicit) return ICONS[explicit] || null;
  const key = normalise(name);
  return ICONS[key] || ICONS[ALIASES[key]] || ICONS[ALIASES[key.replace(/dot/g, "")]] || ICONS[key.replace(/dot/g, "")] || null;
}

// A brand colour bright enough to read on a dark background (dark brands fall back to white).
export function brightBrand(hex) {
  const n = parseInt(hex, 16), r = (n >> 16) & 255, g = (n >> 8) & 255, b = n & 255;
  const lum = (0.2126 * r + 0.7152 * g + 0.0722 * b) / 255;
  if (lum < 0.2) return "#ffffff";
  // Dim brand colours (Odoo's plum, MySQL's blue…) are lifted towards white so they read on dark green.
  const k = lum < 0.5 ? (0.5 - lum) * 1.3 : 0;
  const mix = (c) => Math.round(c + (255 - c) * k).toString(16).padStart(2, "0");
  return "#" + mix(r) + mix(g) + mix(b);
}

export function TechIcon({ name, icon, className = "" }) {
  const found = techIcon(name, icon);
  if (!found) return null;
  return <svg className={"tech-icon " + className} viewBox="0 0 24 24" aria-hidden="true"><path d={found.path} /></svg>;
}
